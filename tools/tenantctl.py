TENANT_PATTERN = re.compile(r"[a-z][a-z0-9-]{1,31}")
API_KEY_ENV = "PTERODACTYL_APPLICATION_API_KEY"
API_ACCEPT = "Application/vnd.pterodactyl.v1+json"
PLAN_VERSION = 1


class TenantError(RuntimeError):
    pass


class PterodactylApiError(TenantError):
    def __init__(self, status_code: int, detail: str) -> None:
        super().__init__(f"Pterodactyl API returned HTTP {status_code}: {detail}")
        self.status_code = status_code


@dataclass(frozen=True)
class Endpoint:
    host: str
    port: int

    @property
    def display(self) -> str:
        host = f"[{self.host}]" if ":" in self.host else self.host
        return f"{host}:{self.port}"


def parse_endpoint(value: str, label: str) -> Endpoint:
    value = value.strip()
    if value.startswith("["):
        closing = value.find("]")
        if closing < 2 or closing + 2 >= len(value) or value[closing + 1] != ":":
            raise TenantError(f"{label} IPv6 addresses must use [address]:port")
        host = value[1:closing]
        port_text = value[closing + 2 :]
    else:
        if value.count(":") != 1:
            raise TenantError(f"{label} must use host:port")
        host, port_text = value.rsplit(":", 1)
    if not host or any(character.isspace() for character in host):
        raise TenantError(f"{label} has an invalid host")
    try:
        port = int(port_text)
    except ValueError as exception:
        raise TenantError(f"{label} port must be a number") from exception
    if not 1 <= port <= 65_535:
        raise TenantError(f"{label} port must be 1..65535")
    return Endpoint(host, port)


def exact_cidr(address: str) -> str:
    import ipaddress

    try:
        parsed = ipaddress.ip_address(address)
    except ValueError as exception:
        raise TenantError(
            "proxy source IP must be a numeric IPv4 or IPv6 address"
        ) from exception
    return f"{parsed.compressed}/{parsed.max_prefixlen}"


def load_settings(path: Path) -> dict[str, Any]:
    try:
        settings = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exception:
        raise TenantError(
            f"cannot read tenant settings from {path}: {exception}"
        ) from exception
    required = (
        "panel_url",
        "egg_id",
        "docker_image",
        "startup",
        "onilink_version",
        "plans",
    )
    missing = [key for key in required if key not in settings]
    if missing:
        raise TenantError(f"tenant settings are missing: {', '.join(missing)}")
    panel_url = str(settings["panel_url"]).rstrip("/")
    if not panel_url.startswith("https://"):
        raise TenantError("panel_url must use HTTPS")
    settings["panel_url"] = panel_url
    if not isinstance(settings["plans"], dict) or not settings["plans"]:
        raise TenantError("plans must be a non-empty object")
    return settings


def validate_tenant(value: str) -> str:
    tenant = value.strip().lower()
    if not TENANT_PATTERN.fullmatch(tenant):
        raise TenantError(
            "tenant must be 2..32 lowercase letters, numbers, or hyphens and start with a letter"
        )
    return tenant


def random_forwarding_secret() -> str:
    return base64.b64encode(secrets.token_bytes(32)).decode("ascii")


